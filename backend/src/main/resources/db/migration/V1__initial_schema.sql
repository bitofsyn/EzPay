CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    auth_provider VARCHAR(255) CHECK (auth_provider IN ('LOCAL', 'KAKAO', 'NAVER')),
    email VARCHAR(255),
    name VARCHAR(255),
    password VARCHAR(255),
    phone_number VARCHAR(255),
    role VARCHAR(255) NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    social_id VARCHAR(255),
    status VARCHAR(255) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    balance NUMERIC(18, 4) NOT NULL,
    is_main BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    account_number VARCHAR(255) NOT NULL UNIQUE,
    bank_name VARCHAR(255),
    CONSTRAINT fk_accounts_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE admin_alerts (
    alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_read BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    message VARCHAR(500) NOT NULL,
    alert_type VARCHAR(255) NOT NULL CHECK (alert_type IN ('WARNING', 'ERROR', 'INFO', 'SUCCESS')),
    title VARCHAR(255) NOT NULL
);

CREATE TABLE admin_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_read BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    sender_id BIGINT NOT NULL,
    content VARCHAR(1000) NOT NULL,
    category VARCHAR(255) NOT NULL CHECK (category IN ('GENERAL', 'LIMIT_REQUEST', 'ACCOUNT_UNLOCK', 'TRANSACTION', 'REPORT')),
    subject VARCHAR(255) NOT NULL,
    CONSTRAINT fk_admin_messages_sender FOREIGN KEY (sender_id) REFERENCES users (user_id)
);

CREATE TABLE error_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP(6),
    error_message VARCHAR(255),
    service_name VARCHAR(255),
    status VARCHAR(255) CHECK (status IN ('RESOLVED', 'UNRESOLVED'))
);

CREATE TABLE failed_event_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retry_count INTEGER,
    last_retried_at TIMESTAMP(6),
    occurred_at TIMESTAMP(6),
    resolved_at TIMESTAMP(6),
    status VARCHAR(20) CHECK (status IN ('PENDING', 'RETRYING', 'RESOLVED', 'RETRY_FAILED')),
    kafka_key VARCHAR(255),
    topic VARCHAR(255) NOT NULL,
    error_message TEXT,
    last_retry_error TEXT,
    payload TEXT
);

CREATE TABLE login_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp" TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    device VARCHAR(255),
    ip VARCHAR(255),
    CONSTRAINT fk_login_history_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    notification_type VARCHAR(255) NOT NULL CHECK (notification_type IN ('EMAIL', 'PUSH')),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE password_reset_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    used BOOLEAN,
    created_at TIMESTAMP(6),
    expiration_time TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    reset_token VARCHAR(255),
    CONSTRAINT fk_password_reset_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE risk_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2) NOT NULL,
    approved_at TIMESTAMP(6),
    transaction_datetime TIMESTAMP(6) NOT NULL,
    level VARCHAR(16) NOT NULL CHECK (level IN ('DANGER', 'CAUTION', 'SAFE')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'BLOCKED')),
    transaction_id VARCHAR(64) NOT NULL,
    reason VARCHAR(500),
    category VARCHAR(255),
    receiver VARCHAR(255) NOT NULL,
    sender VARCHAR(255) NOT NULL
);

CREATE TABLE system_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_time TIMESTAMP(6) NOT NULL,
    level VARCHAR(16) NOT NULL CHECK (level IN ('INFO', 'WARN', 'ERROR', 'DEBUG')),
    message VARCHAR(1000) NOT NULL,
    service VARCHAR(255) NOT NULL
);

CREATE TABLE training_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    category VARCHAR(255),
    memo VARCHAR(255),
    receiver_name VARCHAR(255),
    CONSTRAINT fk_training_data_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE transaction_filters (
    filter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    end_date DATE,
    max_amount NUMERIC(38, 2),
    min_amount NUMERIC(38, 2),
    start_date DATE,
    created_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_transaction_filters_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(38, 2),
    receiver_account_id BIGINT NOT NULL,
    sender_account_id BIGINT NOT NULL,
    transaction_date TIMESTAMP(6),
    request_id VARCHAR(64),
    category VARCHAR(255),
    description VARCHAR(255),
    memo VARCHAR(255),
    status VARCHAR(255) CHECK (status IN ('PROCESSING', 'SUCCESS', 'FAILED', 'CANCELLED', 'HELD', 'BLOCKED')),
    CONSTRAINT uk_transactions_request_id UNIQUE (request_id),
    CONSTRAINT fk_transactions_receiver FOREIGN KEY (receiver_account_id) REFERENCES accounts (account_id),
    CONSTRAINT fk_transactions_sender FOREIGN KEY (sender_account_id) REFERENCES accounts (account_id)
);

CREATE TABLE transfer_limits (
    user_id BIGINT PRIMARY KEY,
    daily_limit NUMERIC(38, 2),
    per_transaction_limit NUMERIC(38, 2),
    CONSTRAINT fk_transfer_limits_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE user_notifications (
    user_notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_read BOOLEAN NOT NULL,
    created_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('TRANSFER', 'DEPOSIT', 'SECURITY')),
    title VARCHAR(100) NOT NULL,
    message VARCHAR(255) NOT NULL,
    CONSTRAINT fk_user_notifications_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE INDEX idx_risk_transactions_transaction_id ON risk_transactions (transaction_id);
CREATE INDEX idx_system_logs_log_time ON system_logs (log_time);
CREATE INDEX idx_transactions_request_id ON transactions (request_id);
CREATE INDEX idx_user_notifications_user_created ON user_notifications (user_id, created_at);
